"""Generates MENDICANT AI's doctrine table, port/linux/game/mendicant/mendicant_doctrine.h,
from tools/mendicant/doctrine.json: the steps, what may follow each for each side, the
defaults, and the chains (the strategies a commander opens with).

    python3 tools/mendicant/doctrine_gen.py [--table <doctrine_table.json>]

--table also writes the doctrine_table.json the trainer's policy.py and export_models.py read
(the ai_brain mod's data/doctrine/doctrine_table.json). After changing doctrine.json, run this,
rebuild, and export the models again: a models file made for another doctrine is refused
(mendicant_doctrine_hash).

The steps' behaviour (who goes where, what ends them) is written by hand in
mendicant_units.c, one case per step; this keeps the table and the code in step, and fails
if a step has no case there.

Ported from the ai_brain hook library's tools/doctrine_gen.py; the table is the same, in C89
types (the game's sources have no <stdint.h>).
"""
import argparse
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
HERE = os.path.join(ROOT, "tools", "mendicant")
GAME = os.path.join(ROOT, "port", "linux", "game", "mendicant")
OUTPUT = os.path.join(GAME, "mendicant_doctrine.h")

parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
parser.add_argument("--doctrine", default=os.path.join(HERE, "doctrine.json"))
parser.add_argument("--table", help="also write doctrine_table.json here (for policy.py)")
parser.add_argument("--check", action="store_true", help="fail if mendicant_doctrine.h is out of date")
options = parser.parse_args()

with open(options.doctrine) as file:
    doctrine = json.load(file)
steps = [s["name"] for s in doctrine["steps"]]
index = {name: n for n, name in enumerate(steps)}
END = len(steps)
assert END < 64, "the masks are 64 bits"
sides = ("covenant", "marines")
PHASES = ("no_contact", "contact", "consolidation", "break_contact", "defense")
RULES = ("normal", "defense", "suspended")


def for_side(entry_for, side):
    return entry_for in ("both", side)


successors = {side: [0] * END for side in sides}
contact_successors = {side: [0] * END for side in sides}
for transition in doctrine["transitions"]:
    source, target = transition["from"], transition["to"]
    if source not in index:
        sys.exit("transition from an unknown step: %s" % source)
    bit = END if target in ("end", "done", "new_strategy") else index.get(target)
    if bit is None:
        sys.exit("transition to an unknown step: %s" % target)
    side_of = transition.get("for", "both")
    for side in sides:
        step = doctrine["steps"][index[source]]
        if not for_side(step["for"], side) or not for_side(side_of, side):
            continue
        if bit != END and not for_side(doctrine["steps"][bit]["for"], side):
            continue
        successors[side][index[source]] |= 1 << bit
        # a reply to contact: any step that fights (not a rest, not consolidation)
        if bit != END:
            target_step = doctrine["steps"][bit]
            resting = target_step["phase"] in ("no_contact", "consolidation") or target_step["name"].startswith("post_")
            if not resting:
                contact_successors[side][index[source]] |= 1 << bit

defaults = {side: [END] * END for side in sides}
fallbacks = {side: [END] * END for side in sides}
for step in doctrine["steps"]:
    for side in sides:
        default = step.get("default_next")
        by_side = step.get("default_for") or {}
        if isinstance(by_side, dict) and by_side.get(side):
            default = by_side[side]
        fallback = step.get("fallback_next")
        if isinstance(default, dict):
            default = default.get(side)
        if isinstance(fallback, dict):
            fallback = fallback.get(side)
        for table, value in ((defaults, default), (fallbacks, fallback)):
            if value in index and for_side(doctrine["steps"][index[value]]["for"], side):
                table[side][index[step["name"]]] = index[value]
            elif value in index:
                table[side][index[step["name"]]] = defaults[side][index[step["name"]]]

chains = doctrine["chains"]
for chain in chains:
    for step in chain["steps"]:
        if step not in index:
            sys.exit("chain %s: unknown step %s" % (chain["name"], step))
longest = max(len(c["steps"]) for c in chains)


def c_name(name):
    return "STEP_" + re.sub(r"[^A-Za-z0-9]", "_", name).upper()


lines = ["/* mendicant_doctrine.h: MENDICANT AI's doctrine (port/linux/game/mendicant), private to the",
    "command layer (mendicant_units.c). Generated by tools/mendicant/doctrine_gen.py from",
    "tools/mendicant/doctrine.json. Do not edit. */",
    "#ifndef HALO_MENDICANT_DOCTRINE_H", "#define HALO_MENDICANT_DOCTRINE_H", ""]
lines.append("enum doctrine_step {")
lines += ["    %s = %d," % (c_name(name), n) for n, name in enumerate(steps)]
lines += ["    STEP_END = %d, /* the strategy is done: a new one is chosen */" % END, "    STEPS = %d" % END, "};", ""]
lines.append("enum { PHASE_%s };" % ", PHASE_".join(p.upper() for p in PHASES))
lines.append("enum { FAILURE_%s };" % ", FAILURE_".join(r.upper() for r in RULES))
lines.append("enum { SIDE_COVENANT, SIDE_MARINES };")
lines.append("static const char *const step_names[STEPS] = { %s };" % ", ".join('"%s"' % n for n in steps))
lines.append("static const signed char step_phase[STEPS] = { %s };" % ", ".join(
    str(PHASES.index(s["phase"])) for s in doctrine["steps"]))
lines.append("static const signed char step_failure_rule[STEPS] = { %s };" % ", ".join(
    str(RULES.index(s.get("failure_rule", "normal"))) for s in doctrine["steps"]))
lines.append("static const short step_cap_ticks[STEPS] = { %s };" % ", ".join(
    str(int(round(float(s["max_seconds"]) * 30))) for s in doctrine["steps"]))
lines.append("static const unsigned char step_splits[STEPS] = { %s };" % ", ".join(
    "1" if s.get("splits") else "0" for s in doctrine["steps"]))
lines.append("static const unsigned char step_sides[STEPS] = { %s }; /* bit 0 Covenant, bit 1 Marines */" % ", ".join(
    str((1 if for_side(s["for"], "covenant") else 0) | (2 if for_side(s["for"], "marines") else 0)) for s in doctrine["steps"]))
for name, table in (("step_successors", successors), ("step_contact_successors", contact_successors)):
    lines.append("static const unsigned long long %s[2][STEPS] = {" % name)
    for side in sides:
        lines.append("    { %s }," % ", ".join("0x%xull" % v for v in table[side]))
    lines.append("};")
for name, table in (("step_default_next", defaults), ("step_fallback_next", fallbacks)):
    lines.append("static const signed char %s[2][STEPS] = {" % name)
    for side in sides:
        lines.append("    { %s }," % ", ".join(str(v) for v in table[side]))
    lines.append("};")
lines.append("#define CHAINS %d" % len(chains))
lines.append("#define CHAIN_STEPS %d" % longest)
lines.append("static const char *const chain_names[CHAINS] = { %s };" % ", ".join('"%s"' % c["name"] for c in chains))
lines.append("static const signed char chain_side[CHAINS] = { %s };" % ", ".join(
    "SIDE_COVENANT" if c["for"] == "covenant" else "SIDE_MARINES" for c in chains))
lines.append("static const signed char chain_length[CHAINS] = { %s };" % ", ".join(str(len(c["steps"])) for c in chains))
lines.append("static const signed char chain_steps[CHAINS][CHAIN_STEPS] = {")
for chain in chains:
    lines.append("    { %s }, /* %s */" % (", ".join(c_name(s) for s in chain["steps"]), chain["name"]))
lines.append("};")
lines += ["", "#endif", ""]
text = "\n".join(lines)

if options.check:
    with open(OUTPUT) as file:
        if file.read() != text:
            sys.exit("%s is out of date: run tools/mendicant/doctrine_gen.py" % os.path.relpath(OUTPUT, ROOT))
else:
    with open(OUTPUT, "w") as file:
        file.write(text)

if options.table:
    with open(options.table, "w") as file:
        json.dump(dict(steps=steps, chains=[dict(name=c["name"], side=c["for"]) for c in chains]), file, indent=1)

# every step must have its case in mendicant_units.c
with open(os.path.join(GAME, "mendicant_units.c")) as file:
    source = file.read()
missing = [name for name in steps if "case %s:" % c_name(name) not in source]
print("doctrine: %d steps, %d chains (longest %d), %d transitions" % (len(steps), len(chains), longest,
    len(doctrine["transitions"])))
if missing:
    sys.exit("mendicant_units.c has no case yet for: %s" % ", ".join(missing))
