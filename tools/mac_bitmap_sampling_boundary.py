#!/usr/bin/env python3
"""Generate the native-only pixel32 fix around the original bitmap sampler."""
from pathlib import Path
import argparse

SOURCE = Path("source/bitmaps/bitmaps.c")
ANCHOR = "\t\t\treturn pixel;\n\t\t}\n\n\t\tif (TEST_FLAG(bitmap->flags, _bitmap_swizzled_bit))"
REPLACEMENT = """#if defined(__ppc__)
			/* port: S3TC returns BGRA bytes; publish the numeric A8R8G8B8 value. */
			pixel = ((pixel & 0x000000FF) << 24) |
				((pixel & 0x0000FF00) << 8) |
				((pixel & 0x00FF0000) >> 8) |
				((pixel & 0xFF000000) >> 24);
#endif
			return pixel;
		}

		if (TEST_FLAG(bitmap->flags, _bitmap_swizzled_bit))"""


def generate(source_path: Path, output_path: Path) -> None:
    source = source_path.read_text(encoding="utf-8")
    count = source.count(ANCHOR)
    if count != 1:
        raise SystemExit(f"Expected one compressed-sampler return anchor, found {count}")
    if REPLACEMENT in source:
        raise SystemExit("Native PPC pixel packing replacement is already present in source")
    output_path.parent.mkdir(parents=True, exist_ok=True)
    generated = source.replace(ANCHOR, REPLACEMENT, 1)
    output_path.write_text(
        "/* Native build view generated by tools/mac_bitmap_sampling_boundary.py. */\n"
        '#line 1 "source/bitmaps/bitmaps.c"\n'
        + generated,
        encoding="utf-8",
    )


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "output",
        nargs="?",
        type=Path,
        default=Path("build/mac-audit/mac_engine_bitmaps_body.h"),
    )
    parser.add_argument("--source", type=Path, default=SOURCE)
    args = parser.parse_args()
    generate(args.source, args.output)
