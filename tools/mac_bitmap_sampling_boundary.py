#!/usr/bin/env python
"""Generate the native-only pixel32 fix around the original bitmap sampler.
Runs on Python 2.6 and 3: usage mac_bitmap_sampling_boundary.py [OUTPUT]
"""
import sys
from mac_gen_io import read_text, write_text

SOURCE = "source/bitmaps/bitmaps.c"
ANCHOR = "\t\t\treturn pixel;\n\t\t}\n\n\t\tif (TEST_FLAG(bitmap->flags, _bitmap_swizzled_bit))"
REPLACEMENT = """#if defined(__ppc__)
			/* port: S3TC returns BGRA bytes; publish the numeric A8R8G8B8 value. */
			pixel = ((pixel & 0x000000FF) << 24) |
				((pixel & 0x0000FF00) << 8) |
				((pixel & 0x00FF0000) >> 8) |
				((pixel & 0xFF000000) >> 24);
#endif
			return pixel;
		}

		if (TEST_FLAG(bitmap->flags, _bitmap_swizzled_bit))"""


def generate(source_path, output_path):
    source = read_text(source_path)
    count = source.count(ANCHOR)
    if count != 1:
        raise SystemExit("Expected one compressed-sampler return anchor, found %d" % count)
    if REPLACEMENT in source:
        raise SystemExit("Native PPC pixel packing replacement is already present in source")
    generated = source.replace(ANCHOR, REPLACEMENT, 1)
    write_text(
        output_path,
        "/* Native build view generated by tools/mac_bitmap_sampling_boundary.py. */\n"
        '#line 1 "source/bitmaps/bitmaps.c"\n'
        + generated)


if __name__ == "__main__":
    generate(SOURCE, sys.argv[1] if len(sys.argv) > 1 else "build/mac-audit/mac_engine_bitmaps_body.h")
