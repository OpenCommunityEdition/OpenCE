#!/usr/bin/env python3
"""Emit only the original check_memory_status implementation for native Mac."""
import os
import sys

source = open("source/cseries/debug_memory.c", "r").read()
signature = "void check_memory_status("
start = source.find(signature)
if start < 0 or source.find(signature, start + len(signature)) >= 0:
    raise SystemExit("expected exactly one original check_memory_status")
brace = source.find("{", start)
depth = 0
end = None
for index in range(brace, len(source)):
    if source[index] == "{":
        depth += 1
    elif source[index] == "}":
        depth -= 1
        if depth == 0:
            end = index + 1
            break
if end is None:
    raise SystemExit("unterminated check_memory_status")
body = source[start:end]
output = sys.argv[1]
directory = os.path.dirname(output)
if directory and not os.path.isdir(directory):
    os.makedirs(directory)
handle = open(output, "w")
handle.write('''/* Generated by tools/mac_memory_diagnostics_view.py from the original game. */
#define BUILDING_CSERIES 1
#include "engine_xdk_prefix.h"
#include "cseries/errors.h"
#include <stdio.h>
struct memory_status
{
    unsigned long minimum_available_memory;
    unsigned long maximum_available_memory;
};
''' + body + '''

/* Native debug_malloc uses the host allocator and has no Xbox debug header
   or allocation ledger. Say so explicitly instead of claiming to enumerate
   allocations that this process cannot safely identify. */
static void native_debug_dump_unavailable(const char *scope)
{
    fprintf(stderr,"native memory dump unavailable (%s): native allocations are not tracked\\n",
        scope?scope:"all allocations");
}

void debug_dump_memory_for_file(const char *file)
{
    native_debug_dump_unavailable(file?file:"requested file");
}

void debug_dump_memory_by_file(void)
{
    native_debug_dump_unavailable("by file");
}

void debug_dump_memory(void)
{
    native_debug_dump_unavailable("all allocations");
}
''')
handle.close()
