#!/usr/bin/env python3
"""Writes gl_simple.inc for tools/mac_gl_record_interpose.c and tools/mac_gl_replay.c:
the GL calls whose arguments are all scalars (one table, so the recorder and
the replay cannot disagree).  usage: mac_gl_replay_gen.py out.inc"""
import sys

# name, return type, [argument types], flags: P = not recorded before the
# captured frame, H = the recorder calls hook_<name>(args) first
S = [
 ("glActiveTextureARB", "void", ["GLenum"], "H"),
 ("glBlendColor", "void", ["GLclampf"]*4, ""),
 ("glBlendEquation", "void", ["GLenum"], ""),
 ("glBlendFunc", "void", ["GLenum"]*2, ""),
 ("glBegin", "void", ["GLenum"], "P"),
 ("glEnd", "void", [], "P"),
 ("glLoadIdentity", "void", [], ""),
 ("glMatrixMode", "void", ["GLenum"], ""),
 ("glClear", "void", ["GLbitfield"], "P"),
 ("glClearColor", "void", ["GLclampf"]*4, ""),
 ("glClearDepth", "void", ["GLclampd"], ""),
 ("glClearStencil", "void", ["GLint"], ""),
 ("glColorMask", "void", ["GLboolean"]*4, ""),
 ("glCullFace", "void", ["GLenum"], ""),
 ("glDepthFunc", "void", ["GLenum"], ""),
 ("glDepthMask", "void", ["GLboolean"], ""),
 ("glDepthRange", "void", ["GLclampd"]*2, ""),
 ("glDisable", "void", ["GLenum"], ""),
 ("glEnable", "void", ["GLenum"], ""),
 ("glDisableVertexAttribArray", "void", ["GLuint"], "H"),
 ("glEnableVertexAttribArray", "void", ["GLuint"], "H"),
 ("glDrawBuffer", "void", ["GLenum"], ""),
 ("glReadBuffer", "void", ["GLenum"], ""),
 ("glFrontFace", "void", ["GLenum"], ""),
 ("glPixelStorei", "void", ["GLenum", "GLint"], "H"),
 ("glScissor", "void", ["GLint", "GLint", "GLsizei", "GLsizei"], ""),
 ("glViewport", "void", ["GLint", "GLint", "GLsizei", "GLsizei"], ""),
 ("glStencilFunc", "void", ["GLenum", "GLint", "GLuint"], ""),
 ("glStencilMask", "void", ["GLuint"], ""),
 ("glStencilOp", "void", ["GLenum"]*3, ""),
 ("glTexCoord2f", "void", ["GLfloat"]*2, "P"),
 ("glVertex2f", "void", ["GLfloat"]*2, "P"),
 ("glTexEnvf", "void", ["GLenum", "GLenum", "GLfloat"], ""),
 ("glTexEnvi", "void", ["GLenum", "GLenum", "GLint"], ""),
 ("glTexParameterf", "void", ["GLenum", "GLenum", "GLfloat"], "T"),
 ("glTexParameteri", "void", ["GLenum", "GLenum", "GLint"], "T"),
 ("glBufferParameteriAPPLE", "void", ["GLenum", "GLenum", "GLint"], ""),
 ("glCopyTexSubImage2D", "void", ["GLenum"] + ["GLint"]*5 + ["GLsizei"]*2, "P"),
 ("glRenderbufferStorageEXT", "void", ["GLenum", "GLenum", "GLsizei", "GLsizei"], ""),
 ("glEndQueryARB", "void", ["GLenum"], "P"),
 ("glCheckFramebufferStatusEXT", "GLenum", ["GLenum"], ""),
]

def kind(t):
    if t in ("GLfloat", "GLclampf"): return "f"
    if t in ("GLdouble", "GLclampd"): return "d"
    return "i"

def words(types): return sum(2 if kind(t) == "d" else 1 for t in types)

out = []
out.append("/* generated by tools/mac_gl_replay_gen.py; do not edit */")
out.append("#ifdef GLR_GEN_ENUM")
for n, r, a, f in S: out.append("OP_%s," % n)
out.append("#endif")
out.append("#ifdef GLR_GEN_NAMES")
for n, r, a, f in S: out.append('"%s",' % n)
out.append("#endif")
out.append("#ifdef GLR_GEN_WRAPPERS")
for n, r, a, f in S:
    params = ", ".join("%s a%d" % (t, i) for i, t in enumerate(a)) or "void"
    nw = words(a)
    body = []
    if nw: body.append("    unsigned w[%d];" % nw)
    k = 0
    for i, t in enumerate(a):
        kd = kind(t)
        if kd == "i": body.append("    w[%d] = (unsigned)a%d;" % (k, i)); k += 1
        elif kd == "f": body.append("    w[%d] = f2u(a%d);" % (k, i)); k += 1
        else: body.append("    d2w((double)a%d, w + %d);" % (i, k)); k += 2
    args = ", ".join("a%d" % i for i in range(len(a)))
    if "H" in f: body.append("    hook_%s(%s);" % (n, args))
    if "T" in f: body.append("    hook_texparam(a0);")
    body.append("    rec_simple(OP_%s, %s, %d, %d);" % (n, "w" if nw else "0", nw, 1 if "P" in f else 0))
    call = "%s(%s);" % (n, args)
    if r != "void": body.append("    return " + call)
    else: body.append("    " + call)
    out.append("static %s w_%s(%s)\n{\n%s\n}" % (r, n, params, "\n".join(body)))
out.append("#endif")
out.append("#ifdef GLR_GEN_INTERPOSE")
for n, r, a, f in S: out.append("    INTERPOSE(w_%s, %s)," % (n, n))
out.append("#endif")
out.append("#ifdef GLR_GEN_PLAY")
for n, r, a, f in S:
    k = 0; args = []
    for t in a:
        kd = kind(t)
        if kd == "i": args.append("(%s)w[%d]" % (t, k)); k += 1
        elif kd == "f": args.append("u2f(w[%d])" % k); k += 1
        else: args.append("w2d(w + %d)" % k); k += 2
    out.append("    case OP_%s: %s(%s); break;" % (n, n, ", ".join(args)))
out.append("#endif")
open(sys.argv[1], "w").write("\n".join(out) + "\n")
