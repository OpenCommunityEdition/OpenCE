"""Emit exact native storage types for missing debug commons, from consumers."""
import argparse
import re
from pathlib import Path

NAMES = """
collision_debug collision_debug_features collision_debug_spray
collision_debug_flag_back_facing_surfaces
collision_debug_flag_ignore_breakable_surfaces
collision_debug_flag_ignore_two_sided_surfaces
collision_debug_flag_objects_bipeds collision_debug_flag_objects_controls
collision_debug_flag_objects_equipment collision_debug_flag_objects_light_fixtures
collision_debug_flag_objects_machines collision_debug_flag_objects_placeholders
collision_debug_flag_objects_projectiles collision_debug_flag_objects_scenery
collision_debug_flag_objects_vehicles collision_debug_flag_objects_weapons
collision_debug_flag_skip_passthrough_bipeds
collision_debug_flag_try_to_keep_location_valid collision_debug_flag_use_vehicle_physics
debug_leaf_index debug_leaf_portal_index debug_leaf_portals debug_objects
profile_display debug_texture_cache debug_sound_environment
collision_debug_flags collision_debug_phantom_bsp_point
global_ai_debug_string_position
""".split()
SOURCES = ['source/physics/collision_debug.c', 'source/hs/hs_globals_external.c',
           'source/ai/ai_debug.h']

def generate():
    declarations = {}
    for source in SOURCES:
        text = re.sub(r'/\*.*?\*/|//[^\n]*', '', Path(source).read_text(), flags=re.S)
        for typ, name in re.findall(r'^extern\s+(boolean|long|unsigned\s+long|real_point3d|short)\s+(\w+)\s*;', text, re.M):
            if name in declarations and declarations[name] != typ:
                raise ValueError('inconsistent consumer declarations: ' + name)
            declarations[name] = typ
    out = ['/* Generated by tools/mac_debug_globals.py from actual consumer declarations.',
           '   Zero-initialized debug settings only; no gameplay service initialization. */']
    out += ['#include "math/real_math.h"']
    for name in NAMES:
        typ = declarations[name]
        size = {'boolean': 1, 'short': 2, 'long': 4, 'unsigned long': 4,
                'real_point3d': 12}[typ]
        out += [f'{typ} {name};', f'typedef char mac_debug_size_{name}[sizeof({name})=={size}?1:-1];']
    return '\n'.join(out) + '\n'

if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    path = Path('port/mac/native_debug_globals.inc')
    content = generate()
    if args.check:
        if path.read_text() != content:
            raise SystemExit('native debug globals are stale; regenerate')
    else:
        path.write_text(content)
    print(f'{len(NAMES)} typed debug globals checked')
