#!/usr/bin/env python3
"""Generate the guest image's host import stubs.

Every function the guest imports from the host (port/android/host_imports.list,
plus the generated OpenGL ES list) gets a stub in the image that loads the
host's 64-bit function address from __host_import_table and branches to it.
The arguments are left untouched in their registers; the host fills in the
table when it loads the image (port/android/host/host_loader.c).

Usage: android_imports.py [--host-table table.c] [--svc] [--host-names names.c]
       output.s list...

With --host-table, also writes the host's name-to-function table for the
names in the lists (OpenGL names, which the host resolves at run time, are
not part of it).

With --svc, for the macOS host, which runs the guest in a VM
(docs/macos_host.md), each stub instead puts the import's index in w16 and
makes an svc, which the guest's EL1 vector turns into an exit to the host;
the host returns to the stub's ret. A hostposix_* stub also keeps the errno
the host leaves in w1 (as Linux's value): it passes it to
guest_import_set_errno (port/android/guest/runtime/guest_misc.c), so that
the wrapper (tools/android_posix_stubs.py) need not ask the host for it with
an exit of its own. --host-names writes the host's list of
the names by that index; the host checks it against the image's
__host_import_names, so that both agree on every index.
"""

import sys


def main():
    arguments = sys.argv[1:]
    host_table = None
    host_names_path = None
    svc = False
    while arguments and arguments[0].startswith("--"):
        option = arguments.pop(0)
        if option == "--host-table":
            host_table = arguments.pop(0)
        elif option == "--host-names":
            host_names_path = arguments.pop(0)
        elif option == "--svc":
            svc = True
        else:
            sys.exit(f"android_imports.py: unknown option {option}")
    output, lists = arguments[0], arguments[1:]
    names = []
    for path in lists:
        for line in open(path, encoding="utf-8"):
            line = line.split("#", 1)[0].strip()
            if line and line not in names:
                names.append(line)
    out = ["/* generated by tools/android_imports.py; do not edit */", "\t.text"]
    # (an index fits mov's 16-bit immediate)
    if svc and len(names) > 0x10000:
        sys.exit("android_imports.py: more imports than an svc stub can number")
    for index, name in enumerate(names):
        offset = index * 8
        out += [
            f"\t.globl {name}",
            f"\t.type {name},%function",
            "\t.p2align 2",
            f"{name}:",
        ]
        if svc and name.startswith("hostposix_"):
            # (the frame is made after the svc: the host reads the arguments
            # past the eighth at the caller's sp; the result, in x0, is kept
            # across the call in the frame; no posix_* function returns a
            # floating-point value, in d0)
            out += [
                f"\tmov w16, #{index}",
                "\tsvc #0",
                "\tstp x29, x30, [sp, #-32]!",
                "\tmov x29, sp",
                "\tstr x0, [sp, #16]",
                "\tmov w0, w1",
                "\tbl guest_import_set_errno",
                "\tldr x0, [sp, #16]",
                "\tldp x29, x30, [sp], #32",
                "\tret",
            ]
        elif svc:
            out += [f"\tmov w16, #{index}", "\tsvc #0", "\tret"]
        else:
            out += [
                f"\tadrp x16, __host_import_table+{offset}",
                f"\tldr x16, [x16, :lo12:__host_import_table+{offset}]",
                "\tbr x16",
            ]
    out += [
        "\t.section .rodata",
        "\t.globl __host_import_names",
        "__host_import_names:",
    ]
    out += [f'\t.asciz "{name}"' for name in names]
    out += [
        "\t.p2align 2",
        "\t.globl __host_import_count",
        "__host_import_count:",
        f"\t.long {len(names)}",
        "\t.data",
        "\t.p2align 3",
        "\t.globl __host_import_table",
        "__host_import_table:",
        f"\t.zero {max(len(names), 1) * 8}",
    ]
    with open(output, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    if host_table:
        host_names = [n for n in names if not n.startswith("hostgl_")]
        table = ["/* generated by tools/android_imports.py; do not edit */",
                 "#include <string.h>", ""]
        def symbol(n):
            # hostposix_<name> imports port/linux/src/posix.h's posix_<name>
            return "posix_" + n[len("hostposix_"):] if n.startswith("hostposix_") else n
        table += [f"extern void {symbol(n)}(void);" for n in host_names]
        table += ["", "static const struct { const char *name; void *function; } imports[] =", "{"]
        table += [f'\t{{ "{n}", (void *){symbol(n)} }},' for n in host_names]
        table += ["};", "",
                  "void *host_resolve_import(const char *name)",
                  "{",
                  "\tunsigned long index;",
                  "",
                  "\tfor (index = 0; index < sizeof(imports) / sizeof(imports[0]); index++)",
                  "\t{",
                  "\t\tif (!strcmp(imports[index].name, name))",
                  "\t\t\treturn imports[index].function;",
                  "\t}",
                  "\treturn NULL;",
                  "}"]
        with open(host_table, "w", encoding="utf-8") as f:
            f.write("\n".join(table) + "\n")
    if host_names_path:
        listing = ["/* generated by tools/android_imports.py; do not edit */", "",
                   "/* the guest's imports by the index its svc stubs pass in w16 */",
                   "const char *const host_import_names[] =", "{"]
        listing += [f'\t"{n}",' for n in names]
        listing += ["};", "", f"const unsigned int host_import_name_count = {len(names)};"]
        with open(host_names_path, "w", encoding="utf-8") as f:
            f.write("\n".join(listing) + "\n")


if __name__ == "__main__":
    main()
