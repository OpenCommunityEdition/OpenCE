#!/usr/bin/env python3
"""Extract the vehicle tag's private C layout from its decompiled source."""
import re
from pathlib import Path

source = Path("source/units/vehicles.c").read_text()
match = re.search(r"struct\s+vehicle_definition\s*\{.*?\};", source, re.S)
if not match:
    raise SystemExit("vehicle_definition not found in source/units/vehicles.c")
layout = match.group(0)
output = """/* Generated by tools/mac_native_vehicle_layout.py from
   source/units/vehicles.c; do not hand edit. */
#ifndef HALO_MAC_NATIVE_VEHICLE_LAYOUT_H
#define HALO_MAC_NATIVE_VEHICLE_LAYOUT_H
#include \"units/unit_definitions.h\"
""" + layout + """
typedef char native_vehicle_definition_size[sizeof(struct vehicle_definition)==0x3f0?1:-1];
typedef char native_vehicle_unit_offset[__builtin_offsetof(struct vehicle_definition,unit)==0x000?1:-1];
typedef char native_vehicle_flags_offset[__builtin_offsetof(struct vehicle_definition,flags)==0x2f0?1:-1];
typedef char native_vehicle_type_offset[__builtin_offsetof(struct vehicle_definition,vehicle_type)==0x2f4?1:-1];
typedef char native_vehicle_modes_offset[__builtin_offsetof(struct vehicle_definition,function_modes)==0x31c?1:-1];
typedef char native_vehicle_suspension_offset[__builtin_offsetof(struct vehicle_definition,suspension_sound)==0x3b0?1:-1];
typedef char native_vehicle_effect_offset[__builtin_offsetof(struct vehicle_definition,effect)==0x3e0?1:-1];
#endif
"""
Path("port/mac/native_vehicle_layout.h").write_text(output)
print("extracted vehicle_definition: 0x3f0 bytes")
