void _rasterizer_environment_fog_begin(
	void)
{
	real atmospheric_eye_density;
	real planar_eye_density;

	match_assert(
		"c:\\halo\\SOURCE\\rasterizer\\xbox\\rasterizer_xbox_environment_fog.c",
		290,
		global_window_parameters.fog.atmospheric_maximum_distance>0.0f);
	match_assert(
		"c:\\halo\\SOURCE\\rasterizer\\xbox\\rasterizer_xbox_environment_fog.c",
		291,
		global_window_parameters.fog.planar_maximum_distance>0.0f);
	match_assert(
		"c:\\halo\\SOURCE\\rasterizer\\xbox\\rasterizer_xbox_environment_fog.c",
		292,
		global_window_parameters.fog.planar_maximum_depth>0.0f);
	match_assert(
		"c:\\halo\\SOURCE\\rasterizer\\xbox\\rasterizer_xbox_environment_fog.c",
		293,
		global_d3d_device);

	rasterizer_profile_begin(_rasterizer_profile_environment_fog);
	if (rasterizer_debug_options.drawing_mode == _rasterizer_drawing_mode_normal &&
		rasterizer_debug_options.draw_environment_fog)
	{
		real distance =
			global_window_parameters.camera_position.x * global_window_parameters.fog.plane.n.i +
			global_window_parameters.camera_position.y * global_window_parameters.fog.plane.n.j +
			global_window_parameters.camera_position.z * global_window_parameters.fog.plane.n.k -
			global_window_parameters.fog.plane.d;

		atmospheric_eye_density = PIN(
			distance / global_window_parameters.fog.atmospheric_maximum_distance,
			0.0f,
			1.0f);
		planar_eye_density = PIN(
			-(distance / global_window_parameters.fog.planar_maximum_depth),
			0.0f,
			1.0f);
		if (TEST_FLAG(global_window_parameters.fog.flags, _fog_definition_atmosphere_dominant_bit))
		{
			atmospheric_eye_density = 1.0f;
			if (distance < -0.3f &&
				rasterizer_environment_fog_screen_globals.atmosphere_dominant_warning_count <
					MAXIMUM_ATMOSPHERE_DOMINANT_WARNINGS)
			{
				error(
					_error_silent,
					"### WARNING camera went below atmosphere-dominant fog plane");
				rasterizer_environment_fog_screen_globals.atmosphere_dominant_warning_count++;
			}
		}

		rasterizer_set_texture_direct(
			0,
			global_rasterizer_data->atmospheric_fog_density.index,
			0);
		IDirect3DDevice8_SetTextureStageState(global_d3d_device, 0, D3DTSS_ADDRESSU, D3DTADDRESS_CLAMP);
		IDirect3DDevice8_SetTextureStageState(global_d3d_device, 0, D3DTSS_ADDRESSV, D3DTADDRESS_CLAMP);
		IDirect3DDevice8_SetTextureStageState(global_d3d_device, 0, D3DTSS_MAGFILTER, D3DTEXF_LINEAR);
		IDirect3DDevice8_SetTextureStageState(global_d3d_device, 0, D3DTSS_MINFILTER, D3DTEXF_LINEAR);
		IDirect3DDevice8_SetTextureStageState(global_d3d_device, 0, D3DTSS_MIPFILTER, D3DTEXF_LINEAR);
		rasterizer_set_texture_direct(
			1,
			global_rasterizer_data->planar_fog_density.index,
			0);
		IDirect3DDevice8_SetTextureStageState(global_d3d_device, 1, D3DTSS_ADDRESSU, D3DTADDRESS_CLAMP);
		IDirect3DDevice8_SetTextureStageState(global_d3d_device, 1, D3DTSS_ADDRESSV, D3DTADDRESS_CLAMP);
		IDirect3DDevice8_SetTextureStageState(global_d3d_device, 1, D3DTSS_MAGFILTER, D3DTEXF_LINEAR);
		IDirect3DDevice8_SetTextureStageState(global_d3d_device, 1, D3DTSS_MINFILTER, D3DTEXF_LINEAR);
		IDirect3DDevice8_SetTextureStageState(global_d3d_device, 1, D3DTSS_MIPFILTER, D3DTEXF_LINEAR);

		IDirect3DDevice8_SetRenderState(global_d3d_device, D3DRS_CULLMODE, D3DCULL_CCW);
		IDirect3DDevice8_SetRenderState(global_d3d_device, D3DRS_COLORWRITEENABLE,
			D3DCOLORWRITEENABLE_RED | D3DCOLORWRITEENABLE_GREEN | D3DCOLORWRITEENABLE_BLUE);
		IDirect3DDevice8_SetRenderState(global_d3d_device, D3DRS_ALPHABLENDENABLE, TRUE);
		IDirect3DDevice8_SetRenderState(global_d3d_device, D3DRS_SRCBLEND, D3DBLEND_ONE);
		IDirect3DDevice8_SetRenderState(global_d3d_device, D3DRS_DESTBLEND, D3DBLEND_INVSRCALPHA);
		IDirect3DDevice8_SetRenderState(global_d3d_device, D3DRS_BLENDOP, D3DBLENDOP_ADD);
		IDirect3DDevice8_SetRenderState(global_d3d_device, D3DRS_ALPHATESTENABLE, TRUE);
		IDirect3DDevice8_SetRenderState(global_d3d_device, D3DRS_ALPHAREF, 0);
		IDirect3DDevice8_SetRenderState(global_d3d_device, D3DRS_ZENABLE, TRUE);
		IDirect3DDevice8_SetRenderState(global_d3d_device, D3DRS_ZFUNC, D3DCMP_EQUAL);
		IDirect3DDevice8_SetRenderState(global_d3d_device, D3DRS_ZWRITEENABLE, FALSE);
		IDirect3DDevice8_SetRenderState(global_d3d_device, D3DRS_ZBIAS, 0);

		csmemset(&pixel_shader, 0, sizeof(pixel_shader));
		pixel_shader.texture_modes = 0x21;
		pixel_shader.combiner_count = 0x11002;
		pixel_shader.constant_0[0] = real_alpha_intensity_to_pixel32(
			global_window_parameters.fog.atmospheric_maximum_density * atmospheric_eye_density,
			global_window_parameters.fog.atmospheric_maximum_density);
		pixel_shader.constant_1[0] = real_alpha_intensity_to_pixel32(
			global_window_parameters.fog.planar_maximum_density * planar_eye_density,
			(1.0f - planar_eye_density) * global_window_parameters.fog.planar_maximum_density);
		pixel_shader.alpha_inputs[0] = 0x02191209;
		pixel_shader.alpha_outputs[0] = 0xC00;
		pixel_shader.rgb_inputs[0] = 0x11180118;
		pixel_shader.rgb_outputs[0] = 0x48;
		pixel_shader.constant_0[1] = real_a_rgb_color_to_pixel32(
			atmospheric_eye_density,
			&global_window_parameters.fog.atmospheric_color);
		pixel_shader.constant_1[1] = real_rgb_color_to_pixel32(
			&global_window_parameters.fog.planar_color);
		pixel_shader.alpha_inputs[1] = 0x283C311C;
		pixel_shader.alpha_outputs[1] = 0xCD;
		pixel_shader.rgb_inputs[1] = 0x0108021C;
		pixel_shader.rgb_outputs[1] = 0xCD;
		pixel_shader.final_combiner_inputs_abcd = 0x0C3D000F;
		pixel_shader.final_combiner_inputs_efg = 0x0D243C00;
		rasterizer_set_pixel_shader(&pixel_shader);
	}

	return;
}

void _rasterizer_environment_fog_draw(
	struct shader const *shader,
	short shader_permutation_index,
	long dynamic_triangle_buffer_index,
	long first_triangle_index,
	long triangle_count,
	struct vertex_buffer const *vertex_buffer)
{
	match_assert(
		"c:\\halo\\SOURCE\\rasterizer\\xbox\\rasterizer_xbox_environment_fog.c",
		423,
		global_d3d_device);
	if (rasterizer_debug_options.drawing_mode == _rasterizer_drawing_mode_normal &&
		rasterizer_debug_options.draw_environment_fog)
	{
		match_assert(
			"c:\\halo\\SOURCE\\rasterizer\\xbox\\rasterizer_xbox_environment_fog.c",
			430,
			shader);
		shader_get_and_verify_type((struct shader *)shader, _shader_type_environment);
		match_assert(
			"c:\\halo\\SOURCE\\rasterizer\\xbox\\rasterizer_xbox_environment_fog.c",
			435,
			vertex_buffer);

		rasterizer_set_vertex_shader_permutation(
			_rasterizer_vertex_shader_environment_fog,
			vertex_buffer->type,
			shader_get_vertex_shader_permutation(shader));
		rasterizer_draw_dynamic_triangles_static_vertices(
			dynamic_triangle_buffer_index,
			first_triangle_index,
			triangle_count,
			vertex_buffer);
		if (rasterizer_debug_options.statistics_mode == _rasterizer_statistics_mode_enabled)
		{
			rasterizer_frame_statistics.environment_fog_dynamic_draw_count++;
			rasterizer_frame_statistics.environment_fog_dynamic_triangle_count += triangle_count;
			rasterizer_frame_statistics.environment_fog_dynamic_vertex_count +=
				rasterizer_frame_statistics_count_dynamic_vertices(
					dynamic_triangle_buffer_index,
					first_triangle_index,
					triangle_count);
		}
	}

	return;
}

