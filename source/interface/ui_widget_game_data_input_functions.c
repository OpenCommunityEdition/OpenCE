void netgame_prejoin_players(
	struct widget_instance *widget)
{
	struct network_game_client *client = global_network_game_client_get();
	union
	{
		long index;
		short client_state_data;
	} state_or_index;
	boolean local_player_wants_to_join[4];

	(void)widget;
	if (client &&
		network_game_client_get_state(client, &state_or_index.client_state_data) == 2)
	{
		struct network_game *game = network_game_get_game();

		match_assert(
			"c:\\halo\\SOURCE\\interface\\ui_widget_game_data_input_functions.c",
			0x614,
			game);

		for (state_or_index.index = 0; (short)state_or_index.index < 4; state_or_index.index++)
		{
			local_player_wants_to_join[(short)state_or_index.index] =
				player_ui_local_player_wants_to_play_multiplayer((short)state_or_index.index);
		}

		for (state_or_index.index = 0; (short)state_or_index.index < 16; state_or_index.index++)
		{
			if (network_player_is_valid(&game->players[(short)state_or_index.index]) &&
				network_game_player_is_local(&game->players[(short)state_or_index.index]))
			{
				local_player_wants_to_join[
					game->players[(short)state_or_index.index].controller_index] = FALSE;
			}
		}

		for (state_or_index.index = 0; (short)state_or_index.index < 4; state_or_index.index++)
		{
			if (local_player_wants_to_join[(short)state_or_index.index] &&
				!network_game_client_add_player(client, (short)state_or_index.index))
			{
				network_event("failed to send join request");
			}
		}
	}
	return;
}

