#ifndef HALO_MAC_XBOX_SWAP_H
#define HALO_MAC_XBOX_SWAP_H
#include <stdint.h>
#include "xbox_map.h"

/* Byte-order conversion of an Xbox map's engine data for big-endian hosts (PowerPC); on a little-endian
   host these do nothing (the map is the engine's own layout). Both are called by mac_cache_files_read
   right after the bytes are copied to their place in the tag cache, so before
   cache_file_tag_header_verify, tag_validate and any other reader of that memory:

   mac_xbox_tag_data_to_native: the tag data (the whole region read at the map header's tag_data_offset,
     tag_data_size bytes) now at `data`, the tag cache base (virtual MAC_XBOX_TAG_BASE): the tag header,
     instances, buffer descriptor tables, and every tag of every group the tables know (xbox_tag_tables.c,
     generated by tools/mac_xbox_tag_tables.py from the engine's own structures), followed through its
     blocks, data and references with every step bounds-checked and every byte walked once only
     (xbox_tag_walk.c), with the data blobs converted by xbox_blob.c. Pointers stay absolute virtual
     addresses (the engine keys on them); only scalars are swapped.
   mac_xbox_bsp_to_native: one bsp read to `data` (bsp->size bytes, virtual bsp->base): its header,
     buffer tables and structure_bsp.
   Return 1 on success; 0 refuses the map (the read then fails with *error).

   The vertex and index data are xbox_geometry.c's, which mac_cache_files_read calls right after these
   (it needs the model parts' and materials' counts and the buffer descriptors in host order).

   Settings (environment): HALO_MAC_XBOX_PPC=refuse keeps the refusal of Xbox maps on a big-endian host;
   HALO_MAC_XBOX_VERIFY=1 reads the converted data back through the same tables and checks it against the
   map's own reading; HALO_MAC_XBOX_SELFTEST=1 (on a little-endian host) runs the whole conversion and
   that verification on a copy of every region the map reads, leaving the engine's own data untouched,
   so that a run on an Intel Mac exercises what a PowerPC would do and renders as it always did. */
int mac_xbox_tag_data_to_native(unsigned char *data, uint32_t size,
    const struct mac_xbox_map_info *info, const char **error);
int mac_xbox_bsp_to_native(unsigned char *data, uint32_t size,
    const struct mac_xbox_bsp *bsp, const struct mac_xbox_map_info *info, const char **error);
/* whether this host may play Xbox maps: 0 (with *why) on a big-endian host where the conversion is
   switched off */
int mac_xbox_swap_supported(const char **why);
/* the map's 0x800-byte cache file header, copied for the engine's cache_file_open: its words (signature,
   version, length, tag data offset and size, checksum, footer signature) into host order. The engine's
   cache_file_header_verify compares them as host values, so a big-endian host refused every map without this. */
void mac_xbox_cache_header_to_native(void *header);
#endif
