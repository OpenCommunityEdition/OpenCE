/*
HOST_MAIN.C

The macOS host (docs/macos_host.md): it runs the guest image in a VM under
Hypervisor.framework. For now it only checks that it may: it creates a VM
and destroys it again, and reports how many imports the guest's stubs
number (host_import_names.c, generated by tools/android_imports.py).
*/

#include <Hypervisor/Hypervisor.h>
#include <stdio.h>

/* (build/macos/host/host_import_names.c) */
extern const char *const host_import_names[];
extern const unsigned int host_import_name_count;

int main(void)
{
	hv_return_t result = hv_vm_create(NULL);

	if (result != HV_SUCCESS)
	{
		fprintf(stderr, "halo_host: cannot create a VM (0x%x); is the host signed with "
			"com.apple.security.hypervisor?\n", (unsigned int)result);
		return 1;
	}
	hv_vm_destroy();
	printf("halo_host: VM created; %u guest imports, the first %s\n",
		host_import_name_count, host_import_name_count ? host_import_names[0] : "(none)");
	return 0;
}
