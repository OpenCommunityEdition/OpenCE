/*
HOST_MAIN.C

The macOS host (docs/macos_host.md): it loads the guest image into guest
memory (the runtime crate checks it, and builds its page tables), checks
that the image's imports are the ones this host numbers, creates the VM,
and runs the guest's __guest_start on the main thread.

  halo_host [image]

The image defaults to halo_guest.elf beside the host, or in
../share/opence (the Nix package's layout). The game's data folder is
HALO_DATA_ROOT, else the current folder.
*/

#include "host.h"

#include <errno.h>
#include <mach-o/dyld.h>
#include <pthread.h>
#include <stdlib.h>
#include <string.h>
#include <sys/stat.h>
#include <unistd.h>

/* (build/macos/host/host_import_names.c, generated by tools/android_imports.py) */
extern const char *const host_import_names[];
extern const unsigned int host_import_name_count;

extern char **environ;

OpenceGuest *host_guest;
OpenceImageInfo host_image_info;
static uint8_t *guest_base;
static pthread_mutex_t allocation_lock = PTHREAD_MUTEX_INITIALIZER;

/* ---------- logging and ending */

/* HALO_HOST_QUIET: only warnings and errors (tests compare the guest's
own output) */
static int quiet = -1;

void host_logf(int priority, const char *format, ...)
{
	va_list arguments;

	if (quiet < 0)
		quiet = getenv("HALO_HOST_QUIET") && *getenv("HALO_HOST_QUIET");
	if (quiet && priority < HOST_LOG_WARN)
		return;
	fputs("halo_host: ", stderr);
	va_start(arguments, format);
	vfprintf(stderr, format, arguments);
	va_end(arguments);
	fputc('\n', stderr);
}

void host_fatal(const char *format, ...)
{
	va_list arguments;

	fputs("halo_host: fatal: ", stderr);
	va_start(arguments, format);
	vfprintf(stderr, format, arguments);
	va_end(arguments);
	fputc('\n', stderr);
	fflush(stderr);
	_exit(71);
}

void host_exit(int code)
{
	host_vm_report_import_counts();
	host_logf(HOST_LOG_INFO, "the guest exited with status %d", code);
	fflush(stdout);
	fflush(stderr);
	exit(code);
}

/* ---------- guest memory */

void *host_guest_pointer(uint32_t address)
{
	return address ? guest_base + address : NULL;
}

uint32_t host_guest_address(const void *pointer)
{
	return pointer ? (uint32_t)((const uint8_t *)pointer - guest_base) : 0;
}

uint32_t host_guest_allocate(uint64_t size)
{
	uint32_t address = 0;
	OpenceStatus status;

	pthread_mutex_lock(&allocation_lock);
	status = opence_guest_allocate(host_guest, size, &address);
	pthread_mutex_unlock(&allocation_lock);
	return status == OPENCE_STATUS_OK ? address : 0;
}

void host_guest_free(uint32_t address, uint64_t size)
{
	/* zeroed, so that the next allocation of it starts zero, as a fresh
	mapping does (memory outside the pools is only zeroed) */
	memset(host_guest_pointer(address), 0, (size_t)size);
	pthread_mutex_lock(&allocation_lock);
	opence_guest_free(host_guest, address, size);
	pthread_mutex_unlock(&allocation_lock);
}

/* ---------- start-up */

static void *read_file(const char *path, size_t *size)
{
	FILE *file = fopen(path, "rb");
	void *data = NULL;
	long length;

	if (!file)
		return NULL;
	if (fseek(file, 0, SEEK_END) == 0 && (length = ftell(file)) > 0 && fseek(file, 0, SEEK_SET) == 0)
	{
		data = malloc((size_t)length);
		if (data && fread(data, 1, (size_t)length, file) != (size_t)length)
		{
			free(data);
			data = NULL;
		}
		*size = (size_t)length;
	}
	fclose(file);
	return data;
}

/* halo_guest.elf beside the executable, or in ../share/opence */
static void default_image_path(char *path, size_t size)
{
	char executable[1024];
	uint32_t length = sizeof(executable);
	struct stat information;
	char *slash;

	snprintf(path, size, "halo_guest.elf");
	if (_NSGetExecutablePath(executable, &length) != 0 || !(slash = strrchr(executable, '/')))
		return;
	*slash = '\0';
	snprintf(path, size, "%s/halo_guest.elf", executable);
	if (stat(path, &information) == 0)
		return;
	snprintf(path, size, "%s/../share/opence/halo_guest.elf", executable);
}

/* copies `text` into guest memory at *cursor; returns its guest address */
static uint32_t put_string(uint32_t *cursor, const char *text)
{
	uint32_t address = *cursor;
	size_t length = strlen(text) + 1;

	memcpy(host_guest_pointer(address), text, length);
	*cursor += (uint32_t)length;
	return address;
}

/* the guest's struct halo_guest_boot: its arguments and environment, in
pool memory. HALO_DATA_ROOT is set (to the current folder if not already),
and so is XDG_DATA_HOME, under which the platform layer keeps saves
(xbox_files.c's platform_save_root): a Mac keeps them in Application
Support, not in ~/.local/share */
static uint32_t boot_block(int argc, char **argv)
{
	char data_root[1024], data_home[1100];
	const char *home = getenv("HOME");
	int environment_count = 0, index, extra = 1;
	size_t strings = 0;
	uint32_t block, cursor, *argv_table, *environment_table;
	struct halo_guest_boot *boot;
	const char *root = getenv("HALO_DATA_ROOT");

	if (root && *root)
		snprintf(data_root, sizeof(data_root), "HALO_DATA_ROOT=%s", root);
	else if (getcwd(data_root + 15, sizeof(data_root) - 15))
		memcpy(data_root, "HALO_DATA_ROOT=", 15);
	else
		snprintf(data_root, sizeof(data_root), "HALO_DATA_ROOT=.");
	data_home[0] = '\0';
	if (!getenv("XDG_DATA_HOME") && home && *home)
	{
		snprintf(data_home, sizeof(data_home), "XDG_DATA_HOME=%s/Library/Application Support/OpenCE", home);
		extra++;
	}
	for (index = 0; index < argc; index++)
		strings += strlen(argv[index]) + 1;
	for (; environ[environment_count]; environment_count++)
		strings += strlen(environ[environment_count]) + 1;
	strings += strlen(data_root) + 1 + strlen(data_home) + 1;

	block = host_guest_allocate(sizeof(*boot) + 4 * ((uint64_t)argc + environment_count + extra + 2) + strings);
	if (!block)
		host_fatal("no guest memory for the arguments");
	boot = host_guest_pointer(block);
	argv_table = (uint32_t *)(boot + 1);
	environment_table = argv_table + argc + 1;
	cursor = host_guest_address(environment_table + environment_count + extra + 1);
	for (index = 0; index < argc; index++)
		argv_table[index] = put_string(&cursor, argv[index]);
	argv_table[argc] = 0;
	for (index = 0; index < environment_count; index++)
		environment_table[index] = put_string(&cursor, environ[index]);
	environment_table[environment_count] = put_string(&cursor, data_root);
	if (data_home[0])
		environment_table[environment_count + 1] = put_string(&cursor, data_home);
	environment_table[environment_count + extra] = 0;
	boot->argc = (uint32_t)argc;
	boot->argv = host_guest_address(argv_table);
	boot->environment = host_guest_address(environment_table);
	/* (the guest's pages: 4 KB, as its page tables) */
	boot->page_size = 4096;
	return block;
}

int main(int argc, char **argv)
{
	char image_path[1100];
	size_t size = 0;
	void *file;
	OpenceStatus status;

	if (argc > 1)
		snprintf(image_path, sizeof(image_path), "%s", argv[1]);
	else
		default_image_path(image_path, sizeof(image_path));
	file = read_file(image_path, &size);
	if (!file)
		host_fatal("cannot read the guest image %s (%s)", image_path, strerror(errno));

	host_guest = opence_guest_create();
	if (!host_guest)
		host_fatal("cannot reserve the guest's 4 GB of address space");
	guest_base = opence_guest_host_base(host_guest);
	status = opence_guest_load_image(host_guest, file, size, &host_image_info);
	free(file);
	if (status != OPENCE_STATUS_OK)
		host_fatal("the guest image %s cannot be loaded: %s", image_path, opence_guest_last_error(host_guest));
	if (opence_guest_check_imports(host_guest, host_import_names, host_import_name_count) != OPENCE_STATUS_OK)
		host_fatal("the guest image does not match this host: %s", opence_guest_last_error(host_guest));
	host_logf(HOST_LOG_INFO, "guest image %08x-%08llx, %u imports", host_image_info.image_start,
		(unsigned long long)host_image_info.image_end, host_image_info.import_count);

	if (host_vm_initialize() != 0)
		return 1;
	host_vm_start_sampler();
	/* (the guest's arguments: from the image's path on, if one was given,
	which so is its argv[0]) */
	host_vm_run_main(boot_block(argc > 1 ? argc - 1 : argc, argc > 1 ? argv + 1 : argv));
}
