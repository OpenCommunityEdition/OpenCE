/*
HOST.H

Internals of the macOS host (docs/macos_host.md), which runs the guest image
in a VM under Hypervisor.framework. Its memory, address-space plan, page
tables and image checks are the runtime crate's (port/macos/runtime,
opence_runtime.h); this side owns the VM and its vCPUs, and carries out the
guest's imports.

The names the Android host's files use (host_logf, host_fatal,
host_call_guest, host_native_thread_create) are kept, so that those files
(port/android/host/host_sdl.c) build here as they are.
*/

#ifndef __HALO_MACOS_HOST_H
#define __HALO_MACOS_HOST_H

#include <stdarg.h>
#include <stddef.h>
#include <stdint.h>
#include <stdio.h>

#include "halo_android_abi.h"
#include "opence_runtime.h"

/* ---------- logging (to the host's standard error, "halo_host: ...") */

void host_logf(int priority, const char *format, ...) __attribute__((format(printf, 2, 3)));
#define HOST_LOG_INFO 4
#define HOST_LOG_WARN 5
#define HOST_LOG_ERROR 6

/* logs and terminates */
void host_fatal(const char *format, ...) __attribute__((format(printf, 1, 2), noreturn));
void host_exit(int code) __attribute__((noreturn));

/* ---------- the guest's memory */

extern OpenceGuest *host_guest;
/* the image's header, as loaded */
extern OpenceImageInfo host_image_info;

/* the host address of guest address `address`; NULL for 0. It is not
checked: the buffers a system call is given are checked by its caller
(host_syscall.c's outside) */
void *host_guest_pointer(uint32_t address);
/* the guest address of host address `pointer` inside guest memory */
uint32_t host_guest_address(const void *pointer);
/* guest pool memory (zero-filled), or 0 */
uint32_t host_guest_allocate(uint64_t size);
/* zeroes guest memory, and gives it back if the pools handed it out */
void host_guest_free(uint32_t address, uint64_t size);

/* ---------- the VM and its vCPUs (host_vm.c) */

/* creates the VM and maps the guest's memory into it, writes the EL1
vectors; 0 on success */
int host_vm_initialize(void);
/* calls the guest function at `function` with up to four 32-bit arguments
on this thread's vCPU (made, with a guest stack, the first time); returns
the guest's w0. A thread with no guest thread pointer gets one first
(__guest_thread_attach), as on Android */
uint32_t host_call_guest(uint32_t function, uint32_t a, uint32_t b, uint32_t c, uint32_t d);
/* starts a host thread running function(argument), which may call guest
code; returns 0 or an errno value */
int host_native_thread_create(void *(*function)(void *), void *argument, size_t stack_size);
/* runs the guest's __guest_start(boot) on this, the main, thread */
void host_vm_run_main(uint32_t boot) __attribute__((noreturn));
/* the import: a host thread running the image's __guest_thread_start(thread) */
int host_thread_create(uint32_t guest_thread, uint32_t stack_size);
/* with HALO_HOST_SAMPLE=<seconds> set, starts a thread that prints each
vCPU's guest address and calls that often */
void host_vm_start_sampler(void);
/* with HALO_HOST_IMPORT_COUNTS set, the number of times the guest called
each import, to standard error ("halo_host: import <name>: <count>") */
void host_vm_report_import_counts(void);
/* this thread's vCPU's TPIDR_EL0: the guest's thread pointer */
uint32_t host_vcpu_thread_pointer(void);
void host_vcpu_set_thread_pointer(uint32_t value);

/* ---------- the guest's imports (host_dispatch.c, generated by
tools/macos_dispatch.py) */

struct host_call
{
	/* x0-x7 as the guest left them */
	uint64_t x[8];
	/* d0-d7 (s0-s7 in their low 32 bits) */
	uint64_t d[8];
	/* the guest's stack pointer, above which are the arguments past the
	registers */
	uint32_t sp;
	/* what goes back in x0 and d0 */
	uint64_t result_x;
	uint64_t result_d;
};

/* carries out import `index` (the w16 of the guest's svc stub); 0 if it
has no such import */
int host_dispatch(struct host_call *call, uint32_t index);
/* the host's errno after this thread's last import: host_errno's (the
host's own work between two imports may change errno itself) */
extern __thread int host_saved_errno;

/* ---------- system calls (host_syscall.c) */

/* the Linux errno value of a host (Darwin) one */
int host_linux_errno(int darwin_errno);

#endif
