/*
MENDICANT_UNITS.C

MENDICANT AI's command layer (M2), its units' side: the battle-drill doctrine
at work, and what the strategic model sees of a unit.

A strategy opens with a chain from the doctrine (mendicant_doctrine.h,
generated by the mod's tools/doctrine_gen.py) and goes on step by step: at
every step's end the strategic model chooses the next step among those the
doctrine allows (the scripted fallback takes the chain's own next step). A
unit has up to three elements (base, maneuver, reserve), each with a role and
a place in the step. Steps with no enemy yet (movement to contact, the
Covenant's postures) use stand-in reference points and end the moment contact
comes. Failure (half the unit lost, or friends dying with no enemy killed
while committed) means a fighting withdrawal, a regroup, the elements evened
out again, and a new strategy.

Ported from the ai_brain hook library (command.inc, and ai_brain.c's plan
memory and plan features); its behaviour is the same.
*/

