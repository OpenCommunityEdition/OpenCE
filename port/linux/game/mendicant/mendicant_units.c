static real distance_to(struct actor_datum *actor, real x, real y, real z)
{
	real dx = actor->input.pathfinding_point.x - x;
	real dy = actor->input.pathfinding_point.y - y;
	real dz = actor->input.pathfinding_point.z - z;

	return (real)sqrt(dx * dx + dy * dy + dz * dz);
}

static real range_to(struct actor_datum *actor, real_point3d const *target)
{
	real x = actor->input.pathfinding_point.x - target->x;
	real y = actor->input.pathfinding_point.y - target->y;

	return (real)sqrt(x * x + y * y);
}

static real signed_angle(real from_x, real from_y, real to_x, real to_y)
{
	return (real)atan2(from_x * to_y - from_y * to_x, from_x * to_x + from_y * to_y) * UNITS_RADIANS_TO_DEGREES;
}

