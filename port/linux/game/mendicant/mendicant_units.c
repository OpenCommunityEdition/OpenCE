/* ---------- the doctrine as the models' runtime needs it (mendicant_doctrine.h stays private here) */

int mendicant_doctrine_chains(void)
{
	return CHAINS;
}

/* the steps the strategic model chooses among, and "done" */
int mendicant_doctrine_step_choices(void)
{
	return STEPS + 1;
}

/* 1 for each chain of the Covenant's */
void mendicant_doctrine_chain_covenant(unsigned char *chain_covenant)
{
	int chain;

	for (chain = 0; chain < CHAINS; chain++)
		chain_covenant[chain] = chain_side[chain] == SIDE_COVENANT;
}

static unsigned long doctrine_hash_text(unsigned long hash, char const *text)
{
	for (; *text; text++)
		hash = ((hash ^ (unsigned char)*text) * 0x01000193UL) & 0xFFFFFFFFUL;
	return hash;
}

/* FNV-1a over the chains (name and side) and steps, the decision layout the
weights were made for: export_weights.py's doctrine_hash, over
"<chain>:<covenant|marines>|...#<step>|..." */
unsigned long mendicant_doctrine_hash(void)
{
	unsigned long hash = 0x811C9DC5UL;
	int chain, step;

	for (chain = 0; chain < CHAINS; chain++)
	{
		if (chain)
			hash = doctrine_hash_text(hash, "|");
		hash = doctrine_hash_text(hash, chain_names[chain]);
		hash = doctrine_hash_text(hash, chain_side[chain] == SIDE_COVENANT ? ":covenant" : ":marines");
	}
	hash = doctrine_hash_text(hash, "#");
	for (step = 0; step < STEPS; step++)
	{
		if (step)
			hash = doctrine_hash_text(hash, "|");
		hash = doctrine_hash_text(hash, step_names[step]);
	}
	return hash;
}
